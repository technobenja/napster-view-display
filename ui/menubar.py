"""The menu bar app. A **separate process** from the
display agent.

Run: `display/.venv/bin/python3 ui/menubar.py`

This file is the AppKit shell and nothing else. Every decision it makes —
which state to show, whether the heartbeat is stale, how to truncate a
label, what the next command file should contain — lives in
`menubar_state.py`, which has no AppKit in it and is where the tests are.
What is left here is the part that can only be verified by looking at a
real menu bar: an `NSStatusItem`, a menu, a timer, and the code that
turns a decision into a `setTitle_` call.

**The two processes never write each other's files**. This one
writes `~/.viewlab/state/command.json` and reads
`~/.viewlab/state/status.json`; the display does exactly the reverse.
There is no other channel between them — no sockets, no notifications,
no shared memory — which is what makes "force-quit the UI and the
pictures keep rotating" true by construction rather than by care.

It also writes a third file, `~/.viewlab/state/ui_status.json`, carrying
one field: `ui_heartbeat_at`, stamped from `pollTick_`. That is **not** a
channel to the display, which never reads it — it is the mirror image of
the display's own `heartbeat_at`, and it exists because `ui.lock` proves
only that this process is *alive*. On 2026-09-08 a wedged menu bar held
that lock while serving nobody, every relaunch found the lock held and
exited 0 exactly as designed, and nothing on the machine could tell that
state from a healthy one. A heartbeat can, because it is written from a
timer: it stops the moment the run loop stops servicing timers, which is
precisely what a wedge is. Nothing in the app reads it yet — acting on
it is a separate, separately-approved change.

**Conventions this file follows, each for a reason already paid for:**

- `@objc.python_method` on every private helper. A plain snake_case
  method on an `NSObject` subclass is exported to the Objective-C
  runtime as a selector, and one of them has already collided with an
  AppKit selector in this project and cost a debugging session.
- A broad `try/except` around the body of **every** selector AppKit
  calls — timer callbacks and menu actions alike. An exception escaping
  an NSTimer selector kills the run loop; an exception escaping a menu
  action lands in AppKit's own dispatch and is at best logged somewhere
  nobody looks. The display agent has carried this rule since Phase 2.
- Reads never raise, writes are atomic write-then-rename (via
  `control.write_control` / `atomic_io`).
"""

